def test_stochastic_matches_hand_calculation():
    # window highs/lows/closes chosen so HH/LL/close are simple round numbers
    highs = pd.Series([10.0, 12.0, 14.0])
    lows = pd.Series([8.0, 9.0, 10.0])
    closes = pd.Series([9.0, 11.0, 13.0])
    # at idx2: HH=max(10,12,14)=14, LL=min(8,9,10)=8, close=13
    # %K = 100*(13-8)/(14-8) = 100*5/6 = 83.333333
    k, d = ind.stochastic_oscillator(highs, lows, closes, k_period=3, d_period=2)
    assert k.iloc[2] == pytest.approx(83.333333, rel=1e-6)


@pytest.mark.parametrize("period", [3, 5])
def test_no_lookahead_bias_sma(period):
    """Truncating the series to any prefix must not change any already-
    computed value in the overlap — an indicator that "knows" about
    future bars would silently invalidate every backtest built on it."""
    full = pd.Series([float(x) for x in [10, 12, 9, 15, 20, 18, 22, 30, 25, 28]])
    full_out = ind.sma(full, period)
    truncated_out = ind.sma(full.iloc[:7], period)
    pd.testing.assert_series_equal(full_out.iloc[:7], truncated_out, check_names=False)


@pytest.mark.parametrize("period", [3, 5])
def test_no_lookahead_bias_rsi(period):
    full = pd.Series([float(x) for x in [10, 12, 9, 15, 20, 18, 22, 30, 25, 28]])
    full_out = ind.rsi(full, period)
    truncated_out = ind.rsi(full.iloc[:7], period)
    pd.testing.assert_series_equal(full_out.iloc[:7], truncated_out, check_names=False)


def test_no_lookahead_bias_atr():
    highs = pd.Series([float(x) for x in [10, 12, 9, 15, 20, 18, 22, 30, 25, 28]])
    lows = highs - 2
    closes = highs - 1
    full_out = ind.atr(highs, lows, closes, period=3)
    truncated_out = ind.atr(highs.iloc[:7], lows.iloc[:7], closes.iloc[:7], period=3)
    pd.testing.assert_series_equal(full_out.iloc[:7], truncated_out, check_names=False)


def test_compute_all_appends_expected_columns_and_does_not_mutate_input():
    dates = pd.date_range("2024-01-01", periods=60, freq="D")
    rng = np.random.RandomState(42)
    close = 100 + np.cumsum(rng.randn(60))
    df = pd.DataFrame({
        "open": close + rng.uniform(-1, 1, 60),
        "high": close + rng.uniform(1, 2, 60),
        "low": close - rng.uniform(1, 2, 60),
        "close": close,
        "volume": rng.uniform(1000, 5000, 60),
    }, index=dates)
    original_columns = list(df.columns)
    out = ind.compute_all(df, atr_period=5, rsi_period=5, bb_period=5, sma_trend_period=10)
    for col in ("sma_trend", "rsi", "macd_line", "macd_signal", "macd_hist",
                "bb_mid", "bb_upper", "bb_lower", "atr", "stoch_k", "stoch_d"):
        assert col in out.columns
    assert list(df.columns) == original_columns, "compute_all must not mutate its input DataFrame"


