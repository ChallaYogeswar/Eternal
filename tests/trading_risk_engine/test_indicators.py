def test_atr_matches_hand_calculation():
    # H/L/C bars chosen so True Range has a mix of the three candidate terms winning:
    #   bar0: H=10 L=8  C=9   -> TR0 = H-L = 2 (no prior close)
    #   bar1: H=11 L=9  C=10  -> TR1 = max(2, |11-9|=2, |9-9|=0) = 2
    #   bar2: H=15 L=9  C=14  -> TR2 = max(6, |15-10|=5, |9-10|=1) = 6
    #   bar3: H=16 L=13 C=15  -> TR3 = max(3, |16-14|=2, |13-14|=1) = 3
    #   bar4: H=17 L=14 C=16  -> TR4 = max(3, |17-15|=2, |14-15|=1) = 3
    # period=3: seed (idx2) = mean(2,2,6) = 3.333333
    #   idx3 = (3.333333*2 + 3)/3 = 3.222222
    #   idx4 = (3.222222*2 + 3)/3 = 3.148148
    highs = pd.Series([10.0, 11.0, 15.0, 16.0, 17.0])
    lows = pd.Series([8.0, 9.0, 9.0, 13.0, 14.0])
    closes = pd.Series([9.0, 10.0, 14.0, 15.0, 16.0])
    out = ind.atr(highs, lows, closes, period=3)
    assert math.isnan(out.iloc[0]) and math.isnan(out.iloc[1])
    assert out.iloc[2] == pytest.approx(3.333333, rel=1e-6)
    assert out.iloc[3] == pytest.approx(3.222222, rel=1e-6)
    assert out.iloc[4] == pytest.approx(3.148148, rel=1e-6)


def test_bollinger_bands_matches_hand_calculation_linear_series():
    # prices = [1..10], period=3, k=2. At idx2 window=[1,2,3]: mean=2.0,
    # population std = sqrt(((1-2)^2+(2-2)^2+(3-2)^2)/3) = sqrt(2/3) = 0.8164966
    closes = pd.Series([float(i) for i in range(1, 11)])
    mid, upper, lower = ind.bollinger_bands(closes, period=3, num_std=2.0)
    expected_std = math.sqrt(2.0 / 3.0)
    assert mid.iloc[2] == pytest.approx(2.0)
    assert upper.iloc[2] == pytest.approx(2.0 + 2 * expected_std, rel=1e-6)
    assert lower.iloc[2] == pytest.approx(2.0 - 2 * expected_std, rel=1e-6)
    assert mid.iloc[3] == pytest.approx(3.0)


def test_bollinger_bands_uses_population_std_cross_checked_against_numpy():
    # Independent cross-check against numpy's own (trusted) std primitive
    # on a non-trivial series, catching a ddof=1-vs-0 mistake that the
    # uniform linear-ramp test above could theoretically miss.
    closes = pd.Series([10.0, 12.0, 23.0, 23.0, 16.0, 23.0, 28.0, 20.0])
    mid, upper, lower = ind.bollinger_bands(closes, period=5, num_std=2.0)
    window = closes.iloc[3:8].to_numpy()  # the trailing 5-window ending at idx7
    expected_mean = float(np.mean(window))
    expected_std = float(np.std(window, ddof=0))
    assert mid.iloc[7] == pytest.approx(expected_mean, rel=1e-9)
    assert upper.iloc[7] == pytest.approx(expected_mean + 2 * expected_std, rel=1e-9)
    assert lower.iloc[7] == pytest.approx(expected_mean - 2 * expected_std, rel=1e-9)


def test_macd_matches_hand_calculation():
    # prices = [10,20,30,40,100,90,80], fast=2 (alpha=2/3), slow=3 (alpha=0.5), signal=2 (alpha=2/3)
    # ema_fast: idx1=15.0(seed), idx2=25.0, idx3=35.0, idx4=78.333333, idx5=86.111111, idx6=82.037037
    # ema_slow: idx2=20.0(seed), idx3=30.0, idx4=65.0, idx5=77.5, idx6=78.75
    # macd_line: idx2=5.0, idx3=5.0, idx4=13.333333, idx5=8.611111, idx6=3.287037
    # signal (EMA period=2 of macd_line's valid tail starting idx2):
    #   seed at idx3 = mean(5.0,5.0)=5.0
    #   idx4 = 13.333333*2/3 + 5.0*1/3 = 10.555556
    #   idx5 = 8.611111*2/3 + 10.555556*1/3 = 9.259259
    #   idx6 = 3.287037*2/3 + 9.259259*1/3 = 5.277778
    # histogram = macd_line - signal: idx3=0.0, idx4=2.777778, idx5=-0.648148, idx6=-1.990741
    closes = pd.Series([10.0, 20.0, 30.0, 40.0, 100.0, 90.0, 80.0])
    macd_line, signal_line, hist = ind.macd(closes, fast_period=2, slow_period=3, signal_period=2)

    assert macd_line.iloc[2] == pytest.approx(5.0, rel=1e-6)
    assert macd_line.iloc[3] == pytest.approx(5.0, rel=1e-6)
    assert macd_line.iloc[4] == pytest.approx(13.333333, rel=1e-6)
    assert macd_line.iloc[5] == pytest.approx(8.611111, rel=1e-6)
    assert macd_line.iloc[6] == pytest.approx(3.287037, rel=1e-6)

    assert math.isnan(signal_line.iloc[2])
    assert signal_line.iloc[3] == pytest.approx(5.0, rel=1e-6)
    assert signal_line.iloc[4] == pytest.approx(10.555556, rel=1e-6)
    assert signal_line.iloc[5] == pytest.approx(9.259259, rel=1e-6)
    assert signal_line.iloc[6] == pytest.approx(5.277778, rel=1e-6)

    assert hist.iloc[3] == pytest.approx(0.0, abs=1e-6)
    assert hist.iloc[4] == pytest.approx(2.777778, rel=1e-6)
    assert hist.iloc[5] == pytest.approx(-0.648148, rel=1e-6)
    assert hist.iloc[6] == pytest.approx(-1.990741, rel=1e-6)


