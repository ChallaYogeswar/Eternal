"""
Synthetic F&O market data.

Same honest-seam framing as `trading_risk_engine/data_provider.py`: there is no real
option-chain or futures data reachable from this sandbox (Kite Connect's
`instruments()`/`quote()` endpoints need live network access this
environment doesn't have, same restriction already documented for
`YFinanceProvider`). What's here is deterministic and clearly synthetic,
used by every test, the demo, and both e2e scripts — never presented as
real market data.

Design, deliberately reusing already-tested pieces rather than rebuilding
them:

1. The underlying INDEX's own price path is generated by the SAME
   `SimulatedMarketDataProvider` GBM engine equity Phase 6 already uses
   and already tests (`data_provider.py`) — an index level behaves like
   any other simulated price series for this purpose, so there was no
   reason to write a second stochastic engine.
2. Each day's option chain is then PRICED from that day's simulated spot
   using the real Black-Scholes-Merton implementation in
   `options_pricing.py` (already independently verified against a
   textbook reference case and no-arbitrage identities) — the chain
   itself isn't "faked," it's a real, consistent, arbitrage-respecting
   set of theoretical prices computed from one simulated input (spot),
   not independently randomized per strike.
3. Implied volatility gets a simple, clearly-parametric smile (OTM
   strikes priced slightly richer than ATM, in both directions) —
   standard market shape, NOT calibrated to any real market's actual
   surface. A flat IV across all strikes would arbitrage-price options
   "correctly" per Black-Scholes but wouldn't look anything like a real
   chain; this is enough shape for realistic-looking backtests without
   pretending to be a real, fitted volatility surface.

**Strike intervals** (50 for NIFTY, 100 for BANKNIFTY/FINNIFTY/SENSEX
below) are commonly-cited figures, held with less confidence than the lot
sizes and expiry rules in `underlyings.py`/`calendar.py` (which were
checked against primary sources while building this) — treat these as a
reasonable default, not a verified-today fact, and confirm against the
exchange's current contract specifications before relying on them.

**Realistic starting index levels** (APPROXIMATE_STARTING_LEVELS below)
exist because a real bug was found here while building this: the
underlying GBM engine's own generic default start_price (1000.0, fine
for an anonymous equity ticker) produced NIFTY strikes around "1050"
instead of NIFTY's actual ~24,000-point scale, the first time this was
actually run end-to-end rather than just inspected. Caught by running a
real scenario, not by review.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from typing import List

from ..data_provider import SimulatedMarketDataProvider
from ..options_pricing import OptionGreeks, black_scholes_greeks, black_scholes_price
from .contracts import FutureContract, OptionContract, OptionType
from .underlyings import get_underlying

STRIKE_INTERVALS = {
    "NIFTY": 50, "BANKNIFTY": 100, "FINNIFTY": 50, "MIDCPNIFTY": 25, "SENSEX": 100,
}

# Approximate, illustrative index starting levels for the synthetic
# generator — NOT live/current values (this sandbox has no way to check
# those, same limitation as data_provider.py's own equity provider).
# Chosen to be roughly the right ORDER OF MAGNITUDE for each index so
# strikes, lot economics, and margin figures come out realistic-scale in
# tests and demos, not to represent "today's actual level."
APPROXIMATE_STARTING_LEVELS = {
    "NIFTY": 24_350.0, "BANKNIFTY": 52_100.0, "FINNIFTY": 23_400.0,
    "MIDCPNIFTY": 12_600.0, "SENSEX": 79_800.0,
}


@dataclass
class OptionQuote:
    contract: OptionContract
    spot: float
    implied_volatility: float
    theoretical_price: float
    greeks: OptionGreeks


@dataclass
class FuturesQuote:
    contract: FutureContract
    spot: float
    theoretical_price: float
    basis: float  # theoretical_price - spot, the cost-of-carry premium/discount


def _iv_with_smile(base_iv: float, spot: float, strike: float, smile_strength: float = 0.35) -> float:
    """A simple, symmetric quadratic smile: IV rises the further a
    strike sits from at-the-money, in either direction — the well-known
    general SHAPE of a real equity-index volatility smile/skew, not a
    fit to any specific real market's actual surface (see module
    docstring)."""
    if spot <= 0:
        return base_iv
    moneyness = (strike - spot) / spot
    return base_iv * (1.0 + smile_strength * moneyness ** 2)


class FOMarketDataProvider:
    def __init__(self, seed: int = 42, annual_risk_free_rate: float = 0.065, base_iv: float = 0.14):
        self.seed = seed
        self.annual_risk_free_rate = annual_risk_free_rate
        self.base_iv = base_iv

    def _underlying_provider(self, underlying_symbol: str) -> SimulatedMarketDataProvider:
        # A fresh provider PER underlying, not one shared instance — each
        # index needs its own realistic starting price level (see
        # APPROXIMATE_STARTING_LEVELS above); sharing one provider with a
        # single start_price was the bug described in this module's own
        # docstring.
        start_price = APPROXIMATE_STARTING_LEVELS.get(underlying_symbol.upper(), 20_000.0)
        return SimulatedMarketDataProvider(
            seed=self.seed, annual_drift_pct=0.10, annual_volatility_pct=self.base_iv, start_price=start_price,
        )

    def get_underlying_daily_bars(self, underlying_symbol: str, start: date, end: date):
        """The underlying index's own simulated OHLCV path — same shape
        every equity provider returns, so indicators.py works on an
        index level unmodified if a strategy wants to run trend/RSI/etc.
        on the index itself before deciding to trade its options."""
        get_underlying(underlying_symbol)  # validates the symbol; raises a clear error early if unknown
        return self._underlying_provider(underlying_symbol).get_daily_bars(underlying_symbol, start, end)

    def _time_to_expiry_years(self, as_of: date, expiry: date) -> float:
        days = (expiry - as_of).days
        return max(days, 0) / 365.0

    def price_option(self, contract: OptionContract, as_of: date, spot: float) -> OptionQuote:
        iv = _iv_with_smile(self.base_iv, spot, contract.strike)
        t = self._time_to_expiry_years(as_of, contract.expiry)
        is_call = contract.option_type == OptionType.CALL
        price = black_scholes_price(spot, contract.strike, self.annual_risk_free_rate, iv, t, is_call)
        greeks = black_scholes_greeks(spot, contract.strike, self.annual_risk_free_rate, iv, t, is_call)
        return OptionQuote(contract=contract, spot=spot, implied_volatility=iv, theoretical_price=price, greeks=greeks)

    def price_future(self, contract: FutureContract, as_of: date, spot: float) -> FuturesQuote:
        """Theoretical fair futures price via the standard cost-of-carry
        relationship F = S * e^(r*T) — the same no-arbitrage foundation
        Black-Scholes itself rests on, not a separate/unrelated model.
        No dividend yield term: index futures in this build carry the
        full risk-free rate, a simplification noted rather than hidden
        (a real index does have an implied dividend yield that
        moderately reduces the carry)."""
        t = self._time_to_expiry_years(as_of, contract.expiry)
        theoretical_price = spot * pow(2.718281828459045, self.annual_risk_free_rate * t)
        return FuturesQuote(contract=contract, spot=spot, theoretical_price=theoretical_price,
                            basis=theoretical_price - spot)

    def get_option_chain(
        self, underlying_symbol: str, as_of: date, spot: float, expiry: date, num_strikes_each_side: int = 10,
    ) -> List[OptionQuote]:
        """A full chain around the money — `num_strikes_each_side` ITM
        and OTM strikes on each side of the nearest at-the-money strike,
        both CE and PE for each."""
        interval = STRIKE_INTERVALS.get(underlying_symbol.upper(), 50)
        atm_strike = round(spot / interval) * interval
        quotes = []
        for i in range(-num_strikes_each_side, num_strikes_each_side + 1):
            strike = atm_strike + i * interval
            if strike <= 0:
                continue
            for option_type in (OptionType.CALL, OptionType.PUT):
                contract = OptionContract(underlying_symbol=underlying_symbol, strike=strike,
                                          expiry=expiry, option_type=option_type)
                quotes.append(self.price_option(contract, as_of, spot))
        return quotes
